param(
    [switch]$SkipClean = $false
)

$ErrorActionPreference = "Stop"

# ============================================
# Setup Logging
# ============================================
$LOG_DIR = "build-logs"
$TIMESTAMP = Get-Date -Format "yyyyMMdd_HHmmss"
