$SUMMARY_FILE = Join-Path $LOG_DIR "build-summary_$TIMESTAMP.txt"

# Create log directory
if (-not (Test-Path $LOG_DIR)) {
    New-Item -ItemType Directory -Path $LOG_DIR -Force | Out-Null
}

# Initialize counters
$TOTAL_BUILDS = 0
$PASSED_BUILDS = 0
$FAILED_BUILDS = 0
$SKIPPED_BUILDS = 0
$BUILD_RESULTS = @()

# Log header
"===========================================" | Out-File -FilePath $LOG_FILE -Encoding utf8
"IP-CSS Build All Variants" | Out-File -FilePath $LOG_FILE -Append -Encoding utf8
"Started: $(Get-Date)" | Out-File -FilePath $LOG_FILE -Append -Encoding utf8
"Host: $env:COMPUTERNAME" | Out-File -FilePath $LOG_FILE -Append -Encoding utf8
"User: $env:USERNAME" | Out-File -FilePath $LOG_FILE -Append -Encoding utf8
"===========================================" | Out-File -FilePath $LOG_FILE -Append -Encoding utf8
"" | Out-File -FilePath $LOG_FILE -Append -Encoding utf8

function Write-Log {
    param(
        [string]$Message,
        [string]$Level = "INFO"
    )
    $timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    $logMessage = "[$timestamp] [$Level] $Message"
    $logMessage | Out-File -FilePath $LOG_FILE -Append -Encoding utf8
    Write-Host $logMessage -ForegroundColor Cyan
}

function Write-Summary {
    param(
        [string]$BuildName,
        [string]$Status,
        [string]$Duration
    )
    $BUILD_RESULTS += [PSCustomObject]@{
        Name = $BuildName
        Status = $Status
        Duration = $Duration
    }
    
    $statusColor = switch ($Status) {
        "PASS" { "Green" }
        "FAIL" { "Red" }
        "SKIP" { "Yellow" }
        default { "White" }
    }
    
    Write-Host "[$Status] $BuildName - $Duration" -ForegroundColor $statusColor
}

function Invoke-GradleBuild {
    param(
        [string]$TaskName,
        [string]$BuildName
    )
    
    Write-Log -Message "Starting: $BuildName"
    $startTime = Get-Date
    
    try {
        $output = & .\gradlew.bat $TaskName --no-daemon --console=plain --info 2>&1
        $exitCode = $LASTEXITCODE
        
        # Log output
        $output | Out-File -FilePath $LOG_FILE -Append -Encoding utf8
        
        $endTime = Get-Date
        $duration = $endTime - $startTime
        
        if ($exitCode -eq 0) {
            Write-Summary -BuildName $BuildName -Status "PASS" -Duration "$($duration.TotalSeconds)s"
            $script:PASSED_BUILDS++
            return $true
        } else {
            Write-Summary -BuildName $BuildName -Status "FAIL" -Duration "$($duration.TotalSeconds)s"
            $script:FAILED_BUILDS++
            return $false
        }
    } catch {
        Write-Log -Message "ERROR: $_" -Level "ERROR"
        $endTime = Get-Date
        $duration = $endTime - $startTime
        Write-Summary -BuildName $BuildName -Status "FAIL" -Duration "$($duration.TotalSeconds)s"
        $script:FAILED_BUILDS++
        return $false
    }
    finally {
        $script:TOTAL_BUILDS++
    }
}

